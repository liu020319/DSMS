CREATE PROCEDURE generate_purchase_data()
BEGIN
    DECLARE i INT DEFAULT 28;
    DECLARE v_user_id BIGINT;
    DECLARE v_prescription_id BIGINT;
    DECLARE v_purchase_date DATE;
    DECLARE v_quantity INT;
    DECLARE v_unit_price DECIMAL(10,2);
    DECLARE v_platform VARCHAR(20);
    DECLARE v_expiry DATE;
    DECLARE v_operator BIGINT;

    WHILE i <= 1200 DO
        SET v_user_id = ELT(FLOOR(1 + RAND() * 5), 1, 3, 4, 5, 6);
        SET v_prescription_id = CASE v_user_id
            WHEN 1 THEN ELT(FLOOR(1 + RAND() * 7), 1, 2, 3, 4, 5, 6, 7)
            WHEN 3 THEN ELT(FLOOR(1 + RAND() * 5), 8, 9, 10, 11, 12)
            WHEN 4 THEN ELT(FLOOR(1 + RAND() * 5), 13, 14, 15, 16, 17)
            WHEN 5 THEN ELT(FLOOR(1 + RAND() * 5), 18, 19, 20, 21, 22)
            WHEN 6 THEN ELT(FLOOR(1 + RAND() * 5), 23, 24, 25, 26, 27)
        END;
        SET v_purchase_date = DATE_ADD('2025-06-01', INTERVAL FLOOR(RAND() * 330) DAY);
        SET v_quantity = ELT(FLOOR(1 + RAND() * 3), 1, 2, 3);
        SET v_unit_price = ROUND(10 + RAND() * 80, 2);
        SET v_platform = ELT(FLOOR(1 + RAND() * 8), '美团买药', '饿了么买药', '京东健康', '阿里健康', '叮当快药', '社区药店', '医院药房', '益丰大药房');
        SET v_expiry = DATE_ADD(v_purchase_date, INTERVAL 365 + FLOOR(RAND() * 365) DAY);
        SET v_operator = 1;

        INSERT INTO purchase_record (user_id, prescription_id, purchase_date, quantity_boxes, unit_price, total_price, expiry_date, operator_id, purchase_platform)
        VALUES (v_user_id, v_prescription_id, v_purchase_date, v_quantity, v_unit_price, v_quantity * v_unit_price, v_expiry, v_operator, v_platform);

        SET i = i + 1;
    END WHILE;
END //
DELIMITER ;

CALL generate_purchase_data();
DROP PROCEDURE IF EXISTS generate_purchase_data;

